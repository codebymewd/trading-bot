"""Generate ea/Include/TrendBotSampleConfig.mqh: a real backend heartbeat response (default config) used by the
EA self-test script, so the MQL5 JSON parser, config mapping and validation are tested on genuine backend output.

  py tools/gen_sample_config.py          (writes)      py tools/gen_sample_config.py --check   (exit 1 if stale)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "ea" / "Include" / "TrendBotSampleConfig.mqh"

from backend.app.config_schema import BrokerConfig, SystemConfig  # noqa: E402


def build() -> str:
    cfg = SystemConfig(broker=BrokerConfig(allowed_logins=[555001]))
    resp = {"server_time": 1700000000, "commands": [{"command_id": "c1", "kind": "PAUSE"}],
            "stale_config_seconds": 300, "config": cfg.ea_payload()}
    text = json.dumps(resp, separators=(",", ":"), sort_keys=True)
    chunks = [text[i:i + 180] for i in range(0, len(text), 180)]
    lines = ["// AUTO-GENERATED by tools/gen_sample_config.py - DO NOT EDIT.", "#property strict", "#ifndef TB_SAMPLE_MQH",
             "#define TB_SAMPLE_MQH", "", "string TB_SampleResponse()", "  {", "   string s = \"\";"]
    for c in chunks:
        esc = c.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'   s += "{esc}";')
    lines += ["   return s;", "  }", "", "#endif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print("wrote", OUT)
